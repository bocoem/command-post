#!/usr/bin/env python3
"""Builds gate/users-page.js (the Users page the gate serves at /users) from gate/users.html,
with the QR code generator (ios/shared/vendor/qrcode.js) built in. Run after editing users.html:
    python3 gate/build_page.py
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
html = open(os.path.join(here, 'users.html'), encoding='utf-8').read()
qr = open(os.path.join(here, '..', 'ios', 'shared', 'vendor', 'qrcode.js'), encoding='utf-8').read()
assert '<!--QRCODE-->' in html
html = html.replace('<!--QRCODE-->', '<script>\n' + qr.replace('</script', '<\\/script') + '\n</script>')
out = '// Generated by gate/build_page.py from gate/users.html. Do not edit by hand.\nexport default ' + json.dumps(html) + ';\n'
open(os.path.join(here, 'users-page.js'), 'w', encoding='utf-8').write(out)
print('users-page.js', len(out), 'bytes')
